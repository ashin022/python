# Exercise 1: Traffic Light Simulator 

color = input("Enter light color: ")

if color == "red":
	print("Stop")
elif color == "yellow":
	print("Slow down")
elif color == "green":
	print("Go")
else:
	print("Invalid color")

# Exercise 2: Even or Odd? 
number = int(input("Enter a whole number: "))

if number % 2 == 0:
	print("Even")
else:
	print("Odd")